package report

// PromptDailyReport 是 GenerateDailyReportAI 使用的 prompt 模板，
// 基于板块汇总数据生成日报的 summary（当日总结）和 outlook（明日展望）。
// %s 占位符依次为：
//
//	0: 日期         "6月9日"
//	1: 整体净流向     "+123亿"
//	2: 流入板块数     "12"
//	3: 流出板块数     "9"
//	4: 流入TOP5      结构化文本
//	5: 流出TOP5      结构化文本
//	6: 资金结构描述   "超大单净流入XX亿…"
//	7: 关键事件时间线 结构化文本
//	8: 新闻摘要       结构化文本
const PromptDailyReport = `你是一名专业的A股资金流向分析师。今天是%s，收盘了，你需要写一份简洁有力的收盘日报。

## 输出格式

严格按以下 JSON 格式输出，不要有任何额外文本：

{
  "summary": "当日总结，150-200字。总览全局，指出今日最核心的资金特征（主线方向、资金偏好、市场情绪），引用具体板块和金额。像在跟机构客户做收盘简报，专业但有观点。",
  "outlook": "明日展望，80-120字。基于今日资金结构给出明日预判，具体到板块方向。"
}

## 今日数据

整体情况：净流向%s，流入%s个板块，流出%s个板块

### 流入TOP5
%s

### 流出TOP5
%s

### 资金结构
%s

### 关键时间线
%s

### 今日重要新闻
%s

## 写作规范

1. summary 要指出主线：今日资金攻击什么方向、回避什么方向
2. 引用具体数据：板块名 + 金额，不要泛泛而谈
3. outlook 要具体：说清楚看好/看空哪个方向，理由是什么
4. 语气专业但不生硬，像在跟同行复盘
5. 不要用"总的来说""总而言之"等废话连接词
6. 不要使用营销口吻，保持分析性`
