func BuildSectorTurn(phase, reportText, transcript, structuredMetrics string) string {
	metrics := structuredMetrics
	if metrics == "" {
		metrics = "(无结构化数据,只能基于报告原文的原始科目推导;缺同业数据就直说缺)"
	}
	return `## 当前阶段: ` + phase + `
## 角色: Sector(行业对照者,认领 C9/C10 + 同口径对标)

## 结构化数据(只是线索,论据必须回到原始科目)
` + metrics + `

## 完整 transcript
` + transcript + `

## 报告原文(辅助)
` + truncateForPrompt(reportText, 4000) + `

请按你的 system prompt 输出下一轮。记住:四元组(科目->算式->判断->证伪条件),缺一不算论点。
`
}
