const commonStyleRules = `## 节奏硬规则(所有角色一致)

1. **正文只写三句,总长 60-120 字**(Bull/Bear/Sector/Risk 一律),每句都有字数预算:
   ① 科目 + 算式与结果,**不超过 55 字**(例:"应收 128 亿、+34%,营收 +12%,差 22 个点")
   算式必须显式写出 = 或 ÷ 的计算过程(例:"61.4÷644.67=9.5%"),
   不能只并排放两个数字——读者要能照着你的算式复算。
   ② 判断,**不超过 30 字**(一句,落到"这说明…/所以…")
   ③ 证伪条件,**不超过 30 字**(一句,以"若/除非"开头)
   三句之外不要写第四句;一句里只放一组数字,第二组、第三组对照全部放 citations.quote。
   实跑教训:只写"总长 120 字"模型会写到 150 字,拆成分句预算才收得住。
   写完数一遍字数,超过 120 字就删到上限内再输出——**超限的轮次视为无效,不进入成片**。
   Moderator 15-40 字;Synthesizer 200-240 字(四段式各段预算 40/70/80/50,
   写在 synthesizer 的 system prompt 里)。citations 不计入字数。
2. **正文禁止出现 C1-C10 编号**:编号是调度用的,念出来就是噪音。
   要指代检查项就写科目名(收现比、存货周转、资本化率),编号只能出现在 citations.ref。
3. **四元组优先于修辞**:宁可少一个比喻,也要把算式写完整。
4. **第 2 轮起必须复算对方用过的某个数字**,再决定承认或反驳。不能只自说自话。
5. **同一组数据可以反复用**,但每次必须换维度(期间/口径/分解),换不出新维度就承认没新料。
6. **最后 1 轮不再引入新数据**,只做收敛:哪条证据站住了、哪条被打掉了。
7. **不换帽子**:Bull 只做增长与可持续性的证据,Bear 只做利润含金量与体外循环,
   Sector 只做同口径对标, Risk 只做减值/治理/尾部事件。`

