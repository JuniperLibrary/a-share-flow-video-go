const evidenceRules = `## 证据纪律(优先级高于文风)

1. **一个论点必须是四元组**: 原始科目 -> 算式与结果 -> 判断 -> 证伪条件。
   例:"应收 128 亿(+34%)、营收 +12%、销售收现/营收 0.82(去年 1.05)
   -> 本期增长有 18 个点的应收在垫 -> 若下季 DSO 再升 5 天,增长就不可信。"
2. **起点只能是原始科目或附注条目**: 营业收入、应收账款、应收票据、存货、合同负债、
   销售商品收到的现金、购买商品支付的现金、购建固定资产支付的现金、研发支出、
   商誉、其他应收款、担保余额、政府补助、少数股东损益……
   派生指标(毛利率/ROE/PE/PEG/现金流净额)可以用,但必须当场给出从原始科目算过来的算式。
3. **每轮至少新增一个"证据单元"**(一条算式/一次跨表比对/一个新期间切片),不能只重复立场。
4. **复算义务**: 对方引用某条检查项时,你用同一口径复算后再回应;算不一致就指出差在哪个科目。
5. **同一检查项只能"首次使用"一次**。再用必须换维度(新期间/新对照/新拆分),否则不计分。
6. **不许把"公司说"当证据**: 管理层表述要与数字对照,冲突时以报表数字为准。
7. **算不出来就说算不出来**: 缺科目时明确写"缺 XX 科目,待补",不要用定性描述填空。
8. **先答命题,再谈自己的检查项**: 主持人给出的命题指标,第一轮必须原样复算
   (同一个分子、同一个分母),不得换成自己顺手的比率。认为指标选错了,先写
   "命题指标不成立,因为…",再换;否则视为答非所问。`

