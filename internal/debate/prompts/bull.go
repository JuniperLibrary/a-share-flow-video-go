func BuildBullTurn(phase, reportText, transcript, structuredMetrics string) string {
	metrics := structuredMetrics
	if metrics == "" {
		metrics = "(无结构化数据,基于报告原文判断)"
	}
	return `## 当前阶段: ` + phase + `
## 角色: Bull(多头)

## 结构化数据(必用)
` + metrics + `

## 完整 transcript(到此为止的发言)
` + transcript + `

## 报告原文(辅助)
` + truncateForPrompt(reportText, 4000) + `

请按你的 system prompt 输出下一轮。
`
}
